const bands = ["sparse", "medium", "dense"];
const source = { title: "Original material written for Street Art Sonification", license: "Original" };
function makeClip(role, id, densityBand, [title, pattern]) {
  return {
    id, role, title, source, lengthBeats: 4, densityBand,
    events: pattern.flatMap(([beat, second, velocity, fourth]) => {
      if (role === "drums" || role === "percussion_texture") return [{ beat, duration: .12, note: second, velocity }];
      if (role === "counter_synth") return [{ beat, duration: second, velocity, chordDegree: [0, 2, 4, 7][fourth] }];
      return Array.from({ length: fourth ?? 1 }, (_, i) => ({
        beat, duration: second, velocity: velocity - 4 * i, previewNote: [60, 64, 67, 71][i],
      }));
    }),
  };
}

