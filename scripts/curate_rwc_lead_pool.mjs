import fs from "node:fs";
import { harmonyForHue } from "../webapp/static/artwork-composition.mjs";
import { rankLeadPhrases } from "../webapp/static/lead-chord-fit.mjs";

const [, , input, output] = process.argv;
if (!input || !output) throw new Error("Pass the extracted JSON and a destination module.");
const { phrases, ...credits } = JSON.parse(fs.readFileSync(input, "utf8"));
const scales = { major: [0, 2, 4, 5, 7, 9, 11], minor: [0, 2, 3, 5, 7, 8, 10] };
const bands = ["sparse", "medium", "dense"];
const byId = new Map();
const fingerprints = new Set();
const fingerprintFor = phrase => JSON.stringify(phrase.events.map(([beat, , pitch]) =>
  [Math.round(beat * 4), pitch - phrase.events[0][2]]));
const rankings = [];
for (const [mode, scale] of Object.entries(scales)) {
  for (const band of bands) {
    const candidates = phrases.filter(p => p.mode === mode && p.densityBand === band);
    for (let hue = 0; hue < 12; hue++) {
      const chordNotes = harmonyForHue(hue, mode).degrees.map(degree =>
        [0, 2, 4, 6].map(offset => {
          const index = degree - 1 + offset;
          return scale[index % 7] + Math.floor(index / 7) * 12;
        }));
      const tracks = new Set();
      const ranked = rankLeadPhrases(candidates, chordNotes);
      rankings.push(ranked);
      for (const { phrase } of ranked) {
        if (tracks.has(phrase.source.track)) continue;
        // Near-identical transcriptions of repeated choruses may have small timing differences.
        const fingerprint = fingerprintFor(phrase);
        if (fingerprints.has(fingerprint) && !byId.has(phrase.id)) continue;
        fingerprints.add(fingerprint);
        tracks.add(phrase.source.track);
        byId.set(phrase.id, phrase);
        if (tracks.size === 5) break;
      }
    }
  }
}

const selected = [...byId.values()];
const supplemental = new Map();
for (const ranked of rankings) {
  const tracks = new Set();
  for (const { phrase, score } of ranked) {
    if (score < ranked[0].score - .018 || tracks.size >= 12) break;
    if (tracks.has(phrase.source.track)) continue;
    const fingerprint = fingerprintFor(phrase);
    if (byId.has(phrase.id) || (fingerprints.has(fingerprint) && !supplemental.has(phrase.id))) continue;
    tracks.add(phrase.source.track);
    fingerprints.add(fingerprint);
    supplemental.set(phrase.id, phrase);
  }
}
const shared = [...selected, ...supplemental.values()];
const exportPhrases = (name, items) => `export const ${name} = [\n${items.map(phrase => `  ${JSON.stringify(phrase)}`).join(",\n")}\n];\n`;
fs.writeFileSync(output,
  "// Generated by scripts/build_rwc_lead_pool.py and scripts/curate_rwc_lead_pool.mjs.\n" +
  "export const rwcLeadCredits = " + JSON.stringify(credits) + ";\n" +
  exportPhrases("rwcLeadPhrases", shared));
console.log(`Curated ${shared.length} phrases from ${new Set(shared.map(p => p.source.track)).size} songs.`);
console.log(`Added ${supplemental.size} supplemental phrases to the shared pool.`);
for (const mode of Object.keys(scales)) {
  console.log(mode, bands.map(band => shared.filter(p => p.mode === mode && p.densityBand === band).length).join(" / "));
}
